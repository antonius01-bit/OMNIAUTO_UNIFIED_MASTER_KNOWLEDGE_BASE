def check_modelopt_environment():
    """Checks whether nvidia-modelopt or torch is available locally."""
    status = {
        "torch_available": False,
        "torch_version": None,
        "cuda_available": False,
        "cuda_device": None,
        "modelopt_installed": False,
        "modelopt_version": None
    }
    
    try:
        import torch
        status["torch_available"] = True
        status["torch_version"] = torch.__version__
        status["cuda_available"] = torch.cuda.is_available()
        if status["cuda_available"]:
            status["cuda_device"] = torch.cuda.get_device_name(0)
    except ImportError:
        pass

    try:
        import modelopt
        status["modelopt_installed"] = True
        status["modelopt_version"] = getattr(modelopt, "__version__", "installed")
    except ImportError:
        pass

    return status

def generate_ptq_recipe(model_name: str, precision: str, output_dir: str) -> str:
    """Generates an end-to-end Python quantization script for a HuggingFace model."""
    precision_map = {
        "fp8": "mtq.FP8_DEFAULT_CFG",
        "int4_awq": "mtq.INT4_AWQ_CFG",
        "nvfp4": "mtq.NVFP4_DEFAULT_CFG",
        "int8_sq": "mtq.INT8_SMOOTHQUANT_CFG"
    }
    cfg_var = precision_map.get(precision.lower(), "mtq.INT4_AWQ_CFG")

    script = f'''# Generated by Dola AI & NVIDIA Model-Optimizer Harness
import os
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
import modelopt.torch.quantization as mtq
from modelopt.torch.export import export_tensorrt_llm_checkpoint

MODEL_ID = "{model_name}"
OUTPUT_DIR = "{output_dir}"

print(f"[*] Loading baseline model: {{MODEL_ID}}")
tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
model = AutoModelForCausalLM.from_pretrained(
    MODEL_ID,
    torch_dtype=torch.float16 if torch.cuda.is_available() else torch.float32,
    device_map="auto"
)

# Calibration forward loop
def forward_loop(model):
    print("[*] Running calibration forward passes...")
    calibration_data = [
        "Explain the key architectural principles of distributed deep learning systems.",
        "Write a concise Python script to implement an LRU cache with threading locks.",
        "Discuss macroeconomic factors influencing foreign direct investment in Southeast Asia.",
        "Perform qualitative thematic coding analysis on employee engagement survey responses."
    ]
    for prompt in calibration_data:
        inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
        with torch.no_grad():
            model(**inputs)

print(f"[*] Applying Quantization: {precision.upper()} with config {cfg_var}")
quantized_model = mtq.quantize(model, {cfg_var}, forward_loop=forward_loop)

print(f"[*] Exporting TensorRT-LLM checkpoint to: {{OUTPUT_DIR}}")
os.makedirs(OUTPUT_DIR, exist_ok=True)
export_tensorrt_llm_checkpoint(
    quantized_model,
    decoder_type="llama",
    dtype="float16",
    export_dir=OUTPUT_DIR,
    inference_tensor_parallel=1
)
print("[✓] Quantization and export completed successfully!")
'''
    return script

def generate_trtllm_build_command(checkpoint_dir: str, engine_dir: str) -> str:
    """Generates the trtllm-build command to compile the quantized checkpoint into an engine."""
    cmd = (
        f"trtllm-build \\\n"
        f"  --checkpoint_dir {checkpoint_dir} \\\n"
        f"  --output_dir {engine_dir} \\\n"
        f"  --gemm_plugin auto \\\n"
        f"  --max_batch_size 32 \\\n"
        f"  --max_input_len 4096 \\\n"
        f"  --max_output_len 2048"
    )
    return cmd

def generate_vllm_serve_command(checkpoint_dir: str, port: int = 8000) -> str:
    """Generates the vLLM serve command using the ModelOpt quantized checkpoint."""
    cmd = f"vllm serve {checkpoint_dir} --quantization modelopt --dtype fp8 --port {port}"
    return cmd

